import fs from 'node:fs';
import path from 'node:path';

// Minimal WebM container with video track header
const target = path.resolve('public/sample-workspace/media/intro-clip.webm');

// Simple valid WebM header sequence
const webmHeader = Buffer.from([
  0x1a, 0x45, 0xdf, 0xa3, // EBML
  0x9f, 0x42, 0x86, 0x81, 0x01, // EBMLVersion = 1
  0x42, 0xf7, 0x81, 0x01, // EBMLReadVersion = 1
  0x42, 0xf2, 0x81, 0x04, // EBMLMaxIDLength = 4
  0x42, 0xf3, 0x81, 0x08, // EBMLMaxSizeLength = 8
  0x42, 0x82, 0x84, 0x77, 0x65, 0x62, 0x6d, // DocType = "webm"
  0x42, 0x87, 0x81, 0x02, // DocTypeVersion = 2
  0x42, 0x85, 0x81, 0x02, // DocTypeReadVersion = 2
  0x18, 0x53, 0x80, 0x67, // Segment
  0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, // Length
  // Info
  0x15, 0x49, 0xa9, 0x66, 0x99,
  0x2a, 0xd7, 0xb1, 0x83, 0x0f, 0x42, 0x40, // TimecodeScale = 1000000
  0x44, 0x89, 0x84, 0x40, 0xa0, 0x00, 0x00, // Duration = 5.0s
  0x4d, 0x80, 0x84, 0x74, 0x65, 0x73, 0x74, // MuxingApp = "test"
  0x57, 0x41, 0x84, 0x74, 0x65, 0x73, 0x74, // WritingApp = "test"
]);

fs.writeFileSync(target, webmHeader);
console.log('Created intro-clip.webm');
